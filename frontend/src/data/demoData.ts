/**
 * Validates leave approval status against departure and return time windows.
 * Enforces business rules:
 * - PENDING or REJECTED leaves are strictly not usable as approved gate passes.
 * - An approved leave is eligible only within its authorized time window.
 * - Leaves outside authorized window are marked NOT_YET_VALID or EXPIRED.
 */
export function checkLeaveValidity(leave: LeaveRequest, refDate: Date = new Date()): {
  status: PassValidityStatus;
  message: string;
  isValid: boolean;
} {
  if (leave.status === 'PENDING') {
    return {
      status: 'PENDING_APPROVAL',
      message: 'Leave application is pending warden review. Digital gate pass not yet issued.',
      isValid: false,
    };
  }
  if (leave.status === 'REJECTED') {
    return {
      status: 'REJECTED',
      message: `Leave application rejected by authority: ${leave.rejectionReason || 'Reason not stated'}. Gate pass void.`,
      isValid: false,
    };
  }
  if (leave.status === 'COMPLETED') {
    return {
      status: 'COMPLETED',
      message: 'Student has already returned to hostel and gate entry was confirmed. Pass concluded.',
      isValid: false,
    };
  }

  // If status is APPROVED or EXPIRED:
  try {
    const departureStr = `${leave.departureDate}T${leave.departureTime}:00`;
    const returnStr = `${leave.returnDate}T${leave.returnTime}:00`;
    const depTime = new Date(departureStr).getTime();
    const retTime = new Date(returnStr).getTime();
    const nowTime = refDate.getTime();

    if (isNaN(depTime) || isNaN(retTime)) {
      return {
        status: leave.status === 'APPROVED' ? 'VALID_ACTIVE' : 'EXPIRED',
        message: 'Pass approved (standard schedule).',
        isValid: leave.status === 'APPROVED',
      };
    }

    if (nowTime < depTime) {
      return {
        status: 'NOT_YET_VALID',
        message: `Pass is not yet active. Authorized departure begins on ${leave.departureDate} at ${leave.departureTime}.`,
        isValid: false,
      };
    }

    if (nowTime > retTime) {
      return {
        status: 'EXPIRED',
        message: `Pass expired on ${leave.returnDate} at ${leave.returnTime}. Curfew deadline passed.`,
        isValid: false,
      };
    }

    return {
      status: 'VALID_ACTIVE',
      message: `Pass is currently valid for exit clearance until ${leave.returnDate} ${leave.returnTime}.`,
      isValid: true,
    };
  } catch {
    return {
      status: 'VALID_ACTIVE',
      message: 'Pass approved.',
      isValid: true,
    };
  }
}

