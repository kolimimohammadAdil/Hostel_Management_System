/**
 * Helper to call the Python OpenCV Face Service.
 */
async function callFaceService(endpoint: string, payload: any): Promise<any> {
  const url = `${config.faceServiceUrl}${endpoint.startsWith('/') ? endpoint : `/${endpoint}`}`;
  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });
    const data = await response.json();
    return { ok: response.ok, status: response.status, data };
  } catch (error: any) {
    throw new Error(`Face Recognition Microservice unreachable at ${config.faceServiceUrl}: ${error.message}`);
  }
}

/**
 * POST /api/biometrics/enroll/:studentId
 * Authorized Warden extracts biometric template from a consented student photograph
 * and securely persists the 128-D embedding in MongoDB Atlas.
 */
export const enrollStudentFace = async (req: Request, res: Response): Promise<void> => {
  try {
    const warden = req.user!;
    const { studentId } = req.params;
    const { image } = req.body;

    if (!image || typeof image !== 'string') {
      res.status(400).json({
        success: false,
        message: 'Valid base64 or Data URL image is required for biometric enrollment',
      });
      return;
    }

    if (mongoose.connection.readyState !== 1) {
      res.status(503).json({
        success: false,
        message: 'Database unavailable. Cannot enroll biometric templates in offline state.',
      });
      return;
    }

    const student = await User.findById(studentId);
    if (!student || student.role !== UserRole.STUDENT) {
      res.status(404).json({
        success: false,
        message: 'Student record not found',
      });
      return;
    }

    // Call Face Recognition Microservice to detect and extract 128-D vector
    const serviceRes = await callFaceService('/extract-embedding', { image });

    if (!serviceRes.ok || !serviceRes.data.success) {
      const errorMsg = serviceRes.data.error || 'Failed to extract face template';
      res.status(400).json({
        success: false,
        message: `Biometric extraction rejected: ${errorMsg}`,
        facesDetected: serviceRes.data.facesDetected ?? 0,
      });
      return;
    }

    const embedding: number[] = serviceRes.data.embedding;
    if (!Array.isArray(embedding) || embedding.length !== 128) {
      res.status(500).json({
        success: false,
        message: 'Invalid biometric embedding format generated by inference engine',
      });
      return;
    }

    // Persist template in MongoDB Atlas
    student.faceEmbedding = embedding;
    student.faceEnrolledAt = new Date();
    student.faceEnrolledBy = warden._id as any;
    await student.save();

    res.status(200).json({
      success: true,
      message: `Biometric face template successfully enrolled for student ${student.fullName}`,
      student: {
        id: student._id,
        fullName: student.fullName,
        rollNumber: student.rollNumber,
        hostelName: student.hostelName,
        faceEnrolledAt: student.faceEnrolledAt,
        isFaceEnrolled: true,
      },
      // Note: raw faceEmbedding is intentionally NEVER returned to the client
      timestamp: new Date().toISOString(),
    });
  } catch (error: any) {
    res.status(500).json({
      success: false,
      message: 'Biometric enrollment failed',
      error: error.message,
    });
  }
};

